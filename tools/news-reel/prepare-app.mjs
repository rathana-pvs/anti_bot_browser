import {bundle} from '@remotion/bundler';
import {ensureBrowser} from '@remotion/renderer';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('.',import.meta.url));
await bundle({entryPoint:root+'src/app.tsx',outDir:root+'app-bundle'});
const browser=await ensureBrowser();
await writeFile(root+'browser.json',JSON.stringify({executablePath:browser.path}));
await writeFile(root+'app-runtime.json',JSON.stringify({daily_brief:1,flexible_scenes:1,lens_report:1,lens_report_revisions:[1,2]}));
console.log('Daily Brief and Lens Report runtime prepared. Refresh capabilities in Studio Center.');
